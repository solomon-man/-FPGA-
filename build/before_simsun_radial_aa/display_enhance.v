// Aligned video: source pixel -> three adjustment stages -> fade -> spectrum/wave -> OSD.
module display_enhance #(
 parameter integer OSD_ENABLE=0,WAVE_ENABLE=0,FADE_FRAMES=0,
 parameter integer BRIGHTNESS=0,CONTRAST=128,AUDIO_WAVE=1,WAVE_LOG_SCALE=1
)(input clk,rst,hs,vs,de,display_valid,frame_start,
 input [23:0] rgb_in,input [3:0] bank,input auto_enabled,
 input [7:0] error_code,input [54:0] parameters,
 input [7:0] alpha,input [9:0] reveal,
 input pcm_valid,input [23:0] pcm_left,pcm_right,
 output reg out_hs,out_vs,out_de,output reg [23:0] rgb_out);
wire signed [8:0] brightness=parameters[28:20];
wire [8:0] contrast=parameters[19:11];
wire [3:0] page={parameters[54],parameters[10:8]};
wire signed [6:0] temperature=parameters[53:47];
wire [4:0] scale={parameters[37:36],parameters[29],parameters[7:6]};
wire [1:0] transition=parameters[5:4],subtitle=parameters[3:2];
wire osd_enable=parameters[1],subtitle_enable=parameters[0];
reg [9:0] x,y,x4,y4,x5,y5,x12,y12,scroll;
reg de_q,frame_pending;
reg [4:0] hpipe,vpipe,dpipe,valid_pipe;
wire [12:0] ux3={x5,2'b00}+x5,uy3={y5,2'b00}+y5,ux2={x4,2'b00}+x4;
wire [12:0] ux12={x12,2'b00}+x12,uy12={y12,2'b00}+y12;
// Coordinate mapping plus seven spectrum clocks. Sidebands follow every pixel.
// The x/y counter depends only on vs/de history, so delayed coordinates are
// regenerated by copies driven from the delayed sidebands instead of being
// shifted through register chains (3.0 area: lets TD hold fixing run).
// x4/y4 = x/y four clocks late; x12/y12 = twelve clocks late.
reg [9:0] fx_x0,fx_y0,fx_x7,fx_y7;reg [7:0] fx_h,fx_v,fx_d,fx_valid;
reg [2:0] osd_h,osd_v,osd_d,osd_valid;
reg [23:0] fx_rgb;wire [23:0] adjusted_q;reg [23:0] photo_q;
always @(posedge clk or posedge rst)begin
 if(rst)begin
  osd_h<=0;osd_v<=0;osd_d<=0;osd_valid<=0;fx_h<=0;fx_v<=0;fx_d<=0;fx_valid<=0;fx_rgb<=0;
  fx_x0<=0;fx_y0<=0;fx_x7<=0;fx_y7<=0;x12<=0;y12<=0;
 end else begin
  osd_h<={osd_h[1:0],fx_h[7]};osd_v<={osd_v[1:0],fx_v[7]};
  osd_d<={osd_d[1:0],fx_d[7]};osd_valid<={osd_valid[1:0],fx_valid[7]};
  fx_x0<=ux3[12:3];fx_y0<=uy3[12:3];fx_rgb<=photo_q;
  // fx_x7 equals fx_x0 seven clocks later: the same mapping of x12.
  fx_x7<=ux12[12:3];fx_y7<=uy12[12:3];
  if(!fx_v[6])begin x12<=0;y12<=0;end
  else if(fx_d[6])x12<=x12+1'b1;
  else begin x12<=0;if(fx_d[7])y12<=y12+1'b1;end
  fx_h<={fx_h[6:0],hpipe[4]};fx_v<={fx_v[6:0],vpipe[4]};
  fx_d<={fx_d[6:0],dpipe[4]};fx_valid<={fx_valid[6:0],valid_pipe[4]};
 end
end
wire [23:0] scaled,adjusted,text_rgb,wave_rgb;
wire scaler_de,scaler_ready;

wire [15:0] r_product=adjusted_q[23:16]*alpha;
wire [15:0] g_product=adjusted_q[15:8]*alpha;
wire [15:0] b_product=adjusted_q[7:0]*alpha;
thumbnail_scaler #(.SOURCE_SCALED(1)) scaler(.clk(clk),.rst(rst),.frame_start(frame_pending),
 .image_bank(bank[1:0]),.de(de && display_valid),.x(x),.y(y),.rgb(rgb_in),.scale(scale),
 .scaled(scaled),.out_de(scaler_de),.ready(scaler_ready));
runtime_adjust_pipeline adjustment(clk,rst,scaled,brightness,contrast,temperature,adjusted_q);
// Visuals follow the music being heard: muted music reads as silence.
// The page-turn chime is mixed later and is not visualised.
wire [1:0] visual_mode=parameters[3:2];
wire music_on=parameters[31],music_muted=parameters[30];
wire signed [23:0] vis_left=music_muted?24'd0:pcm_left;
wire signed [23:0] vis_right=music_muted?24'd0:pcm_right;
wire signed [24:0] vis_sum=vis_left+vis_right;
// Only the selected visual analyses; the other one clears and idles.
wire spectrum_on=music_on && (visual_mode==1 || visual_mode==2);
wire wave_on=AUDIO_WAVE!=0 && music_on && visual_mode==3;
wire [23:0] spectrum_rgb,audio_wave_rgb;
audio_spectrum #(.PIPELINED_RENDER(1)) spectrum(.clk(clk),.rst(rst),.frame_start(frame_start),.de(fx_d[0]),
 .rgb_in(fx_rgb),.x(fx_x0),.y(fx_y0),.mode(visual_mode),.music_enable(spectrum_on),
 .pcm_valid(pcm_valid),.pcm_left(vis_sum[24:9]),.rgb_out(spectrum_rgb));
generate if(AUDIO_WAVE!=0)begin: g_wave
wire [5:0] wave_index;wire [4:0] wave_height;
audio_wave_levels #(.BAR_COUNT(40),.LOG_SCALE(WAVE_LOG_SCALE)) wave_levels(.clk(clk),.rst(rst),
 .enable(wave_on),.frame_start(frame_start),.pcm_valid(pcm_valid),
 .pcm_left(vis_left[23:8]),.pcm_right(vis_right[23:8]),.bar_index(wave_index),.bar_height(wave_height));
audio_wave_overlay wave_overlay(.clk(clk),.rst(rst),.de(fx_d[0]),.enable(wave_on),
 .x(fx_x0),.y(fx_y0),.rgb_in(fx_rgb),.bar_height(wave_height),.bar_index(wave_index),.rgb_out(audio_wave_rgb));
end else begin: g_no_wave
assign audio_wave_rgb=spectrum_rgb;
end endgenerate
// Both renderers take seven clocks; the mode only changes at frame_start.
assign wave_rgb=visual_mode==3?audio_wave_rgb:spectrum_rgb;
text_layers #(.ENABLE_TEMPERATURE(1),.PIPELINED_RENDER(1)) layers(.clk(clk),.rst(rst),.rgb(wave_rgb),.de(fx_d[7]),.x(fx_x7),.y(fx_y7),.page(page),.temperature(temperature),
 .brightness(brightness),.contrast(contrast),.scale(scale),.transition(transition),
 .subtitle(subtitle),.bank(bank),.auto_enabled(auto_enabled),.error_code(error_code),
 .osd_enable(osd_enable || OSD_ENABLE!=0),.subtitle_enable(subtitle_enable),
 .audio_item(parameters[34:33]),.mute(parameters[30]),.music_enable(parameters[31]),.click_enable(parameters[32]),.visual_enable(parameters[35]),
 .music_track(parameters[43:41]),.music_status(parameters[46:44]),.visual_mode(parameters[3:2]),.speed(parameters[39:38]),.speed_toast(parameters[40]),
 .scroll(scroll),.out_rgb(text_rgb));
always @(posedge clk or posedge rst)begin
 if(rst)begin
  x<=0;y<=0;de_q<=0;frame_pending<=0;scroll<=0;
  x4<=0;y4<=0;x5<=0;y5<=0;
  hpipe<=0;vpipe<=0;dpipe<=0;valid_pipe<=0;
  photo_q<=0;out_hs<=0;out_vs<=0;out_de<=0;rgb_out<=0;
 end else begin
  frame_pending<=frame_start;de_q<=de;
  if(!vs)begin x<=0;y<=0;end
  else if(de)x<=x+1'b1;
  else begin x<=0;if(de_q)y<=y+1'b1;end
  if(frame_pending)scroll<=(scroll>=1022)?0:scroll+2;
  if(!vpipe[3])begin x4<=0;y4<=0;end
  else if(dpipe[3])x4<=x4+1'b1;
  else begin x4<=0;if(dpipe[4])y4<=y4+1'b1;end
  x5<=x4;y5<=y4;
  hpipe<={hpipe[3:0],hs};vpipe<={vpipe[3:0],vs};dpipe<={dpipe[3:0],de};
  valid_pipe<={valid_pipe[3:0],display_valid};
  if(ux2[12:3]>=reveal)photo_q<=0;
  else if(alpha==255)photo_q<=adjusted_q;
  else photo_q<={r_product[15:8],g_product[15:8],b_product[15:8]};
  out_hs<=osd_h[2];out_vs<=osd_v[2];out_de<=osd_d[2];
  rgb_out<=osd_valid[2]?text_rgb:24'd0;
 end
end
endmodule
